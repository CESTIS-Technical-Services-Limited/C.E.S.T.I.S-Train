/* Builds trainee-gate/PASTE-GATE.gs — the ONE file an administrator pastes
   into the "CESTIS Trainee Gate" Apps Script project (SETUP.md).

   It is three parts, in this order:
     1. megadata/broker-appsscript/appsscript-prelude.js — the synchronous
        Promise the Apps Script runtime needs (reused from the broker; it
        must come first, and outside Apps Script it changes nothing);
     2. the shared rules from cestis-core.js;
     3. trainee-gate/Gate.gs — the gate's own input and output.

   WHY THERE ARE TWO MODES
   The whole of cestis-core.js is about 0.8 MB, and the gate runs a small
   part of it: Core.gate and the three modules its rules call while it
   answers a request (Core.exams, Core.accountAccess, Core.accountLoginScore)
   plus the few helpers at the top of the file. Every request re-reads the
   whole paste, and whether the Apps Script editor accepts a paste that size
   cannot be checked from here (SETUP.md, live check 1). So by default the
   builder copies ONLY those parts, each one byte for byte from
   cestis-core.js — the design's "allowlist" (DESIGN.md §11) — about a
   quarter of the size.

     node trainee-gate/build-paste.js          the allowlist (the default)
     node trainee-gate/build-paste.js --full   the whole of cestis-core.js

   The mode is written into the file's first lines, and the drift test
   (tests/gate-appsscript-vm.test.js) rebuilds the committed file in the
   mode it says, so switching is: rebuild with --full (or without), commit.
   Both modes run the same scenario in that test, so they behave alike.

   A module the allowlist leaves out but the copied code still names (only
   ever on the staff side: building slices, collecting inboxes) is replaced
   by a guard that THROWS, with this file's name in the message, the moment
   anything touches it — so a rule that starts to need another module fails
   loudly in the test (and, live, in the Executions log), never quietly.
   Run after changing cestis-core.js or Gate.gs:  npm run build:gate */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CORE = 'cestis-core.js';
const PRELUDE = 'megadata/broker-appsscript/appsscript-prelude.js';
const GATE = 'trainee-gate/Gate.gs';

/* The parts of cestis-core.js the gate runs. Each starts at a line that must
   appear exactly once, and ends at the first line after it that equals (or,
   with endPrefix, starts with) the given text. */
const CHUNKS = [
  { name: 'the helpers at the top (Core, hashString, normName, normCourse)',
    start: '  var Core = {};', endPrefix: '  Core.normCourse = function' },
  { name: 'Core.accountLoginScore', start: '  Core.accountLoginScore = function (u) {', end: '  };' },
  { name: 'Core.accountAccess', start: '  Core.accountAccess = (function () {', end: '  })();' },
  { name: 'Core.exams', start: '  Core.exams = (function () {', end: '  })();' },
  { name: 'Core.gate', start: '  Core.gate = (function () {', end: '  })();' }
];

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), 'utf8'); }

/* The allowlisted parts, each a verbatim run of whole lines of the core. */
function chunksOf(coreText) {
  const lines = coreText.split('\n');
  return CHUNKS.map(spec => {
    const at = [];
    lines.forEach((l, i) => { if (l === spec.start) at.push(i); });
    if (at.length !== 1) throw new Error('build-paste: "' + spec.start.trim() + '" found ' + at.length + ' times in ' + CORE + ' (expected once)');
    let end = -1;
    for (let i = at[0]; i < lines.length; i++) {
      if (spec.endPrefix ? lines[i].indexOf(spec.endPrefix) === 0 : (i > at[0] && lines[i] === spec.end)) { end = i; break; }
    }
    if (end < 0) throw new Error('build-paste: no end for ' + spec.name + ' in ' + CORE);
    return { name: spec.name, text: lines.slice(at[0], end + 1).join('\n') };
  });
}

/* Top-level Core modules the copied parts name but do not define. */
function missingModules(chunks) {
  const defined = new Set(), named = new Set();
  chunks.forEach(c => {
    for (const m of c.text.matchAll(/^  Core\.([A-Za-z_$][\w$]*) = /gm)) defined.add(m[1]);
    for (const m of c.text.matchAll(/\bCore\.([A-Za-z_$][\w$]*)/g)) named.add(m[1]);
  });
  return [...named].filter(n => !defined.has(n)).sort();
}

function allowlistCore(coreText) {
  const chunks = chunksOf(coreText);
  const missing = missingModules(chunks);
  let out = '(function (root) {\n  \'use strict\';\n';
  chunks.forEach(c => { out += '\n  /* ---- from cestis-core.js: ' + c.name + ' ---- */\n' + c.text + '\n'; });
  out += [
    '',
    '  /* ---- generated by trainee-gate/build-paste.js: the modules this paste leaves out ----',
    '     The rules above name them only on the staff side (building slices,',
    '     collecting inboxes), which the gate never runs. Touching one throws,',
    '     so a rule that starts to need it fails loudly instead of quietly. */',
    '  ' + JSON.stringify(missing) + '.forEach(function (name) {',
    '    Object.defineProperty(Core, name, { configurable: true, enumerable: false, get: function () {',
    '      throw new Error(\'Core.\' + name + \' is not in the gate\\\'s paste: rebuild it with node trainee-gate/build-paste.js --full\');',
    '    } });',
    '  });',
    '',
    '  root.CESTISCore = Core;',
    '})(typeof globalThis !== \'undefined\' ? globalThis : this);',
    ''
  ].join('\n');
  return { text: out, chunks, missing };
}

function build(mode) {
  mode = mode === 'full' ? 'full' : 'allowlist';
  const coreText = read(CORE);
  const core = mode === 'full' ? { text: coreText, missing: [] } : allowlistCore(coreText);
  const parts = [
    [PRELUDE, 'synchronous Promise for the Apps Script runtime (must be FIRST)', read(PRELUDE)],
    [CORE, mode === 'full' ? 'the shared rules, whole' : 'the shared rules the gate runs (allowlist, byte for byte)', core.text],
    [GATE, 'the gate\'s input and output', read(GATE)]
  ];
  let out = [
    '/* ============================================================================',
    ' * CESTIS Trainee Gate — ALL-IN-ONE Apps Script file.   mode: ' + mode,
    ' * GENERATED by trainee-gate/build-paste.js — do not edit here; edit',
    ' * cestis-core.js or trainee-gate/Gate.gs and run: npm run build:gate',
    ' *',
    ' * SETUP (trainee-gate/SETUP.md): paste this ENTIRE file into a blank',
    ' * project at script.new (replace everything there), save, then',
    ' * Deploy → New deployment → Web app (Execute as: Me / Who has access: Anyone).',
    ' * Nothing to type in: the gate makes its own secret and folders on first use.',
    ' * ==========================================================================*/',
    ''
  ].join('\n');
  for (const [rel, what, text] of parts) {
    out += '\n/* ======== ' + rel + ' — ' + what + ' ======== */\n' + text;
    if (!text.endsWith('\n')) out += '\n';
  }
  return out;
}

/* The mode a built file says it was built in (its first lines). */
function modeOf(text) {
  const m = /mode: (allowlist|full)/.exec(String(text).slice(0, 400));
  return m ? m[1] : null;
}

const artifact = path.join(__dirname, 'PASTE-GATE.gs');
if (module === require.main) {
  const mode = process.argv.indexOf('--full') !== -1 ? 'full' : 'allowlist';
  const text = build(mode);
  fs.writeFileSync(artifact, text);
  console.log('wrote ' + path.relative(ROOT, artifact) + ' (' + mode + ', ' + Buffer.byteLength(text) + ' bytes)');
}
module.exports = { build, modeOf, chunksOf, missingModules, allowlistCore, artifact, CHUNKS };
